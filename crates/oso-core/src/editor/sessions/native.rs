//! A native agent session's buffer (ADR 0165): an internal buffer of
//! [`Mode::NativeSession`] whose text and highlights the host writes from the session's
//! stream, one row's bytes at a time, so that a change costs what it changes and never the
//! whole conversation.
//!
//! Must not depend on: the host's threads, I/O or the session's stream; the host renders a
//! row and gives its text and runs.
//!
//! - The buffer is read-only to keys, as every internal buffer, and withheld from the agent
//!   channel until the person lets agents read it, as a terminal's (ADR 0120, Q16).
//! - It is listed and killed as a person's buffer is; the host learns of the kill as it does
//!   of a terminal's.
//! - A cursor at the end of the text stays at the end as rows come, so a window follows the
//!   conversation unless the person moved away from its end.

use std::ops::Range;

use super::super::Editor;
use super::super::follow::Selected;
use crate::buffer::{Buffer, BufferId, Mode, Replacement};
use crate::syntax::{Highlight, Highlights, Splice};

impl Editor {
    /// Adds an empty native session buffer, `name`, shown in no window yet: internal,
    /// generated by the host and withheld from agents.
    pub fn add_native_session_buffer(&mut self, name: impl Into<String>) -> BufferId {
        let id = self.add_internal_buffer(name, Mode::NativeSession);
        if let Some(buffer) = self.buffer_mut(id) {
            buffer.withhold_from_agents();
        }
        id
    }

    /// Puts `text` in place of the bytes `range` of the native session buffer `id`, with
    /// `runs` laid over the new text as lengths and highlights; the rest keeps its highlights.
    /// The range is clamped to the text and to character starts. O(log n) and the text's
    /// length, with no undo record. Nothing happens to a buffer that is not a native
    /// session's.
    pub fn replace_native_rows(
        &mut self,
        id: BufferId,
        range: Range<usize>,
        text: &str,
        runs: &[(usize, Option<Highlight>)],
    ) {
        let Some(buffer) = self.buffer(id).filter(|buffer| buffer.is_native_session()) else {
            return;
        };
        let (start, end) = buffer.text().clip_range(range);
        let edits = [Replacement {
            range: start..end,
            text,
        }];
        let Some(staged) = buffer.stage_internal(&edits) else {
            return;
        };
        let old_len = buffer.text().len();
        let moved = self.moved_selections(
            id,
            &staged.display(),
            staged.steps(),
            staged.changed(),
            Selected::Logged,
        );
        let views = self.moved_views(id, &staged.display(), staged.steps(), staged.rewrap());
        // Nothing past this point can panic part way.
        if let Some(buffer) = self.buffer_mut(id) {
            let mut highlights = buffer
                .take_generated_highlights()
                .filter(|highlights| highlights.len() == old_len)
                .unwrap_or_else(|| Highlights::new(old_len));
            buffer.commit_internal(staged);
            highlights.splice(&[Splice {
                start,
                old_len: end - start,
                new_len: text.len(),
            }]);
            highlights.replace(start..start + text.len(), runs.iter().copied());
            let _ = buffer.set_generated_highlights(highlights);
        }
        for (index, set) in moved {
            self.windows[index].selections = set;
        }
        self.commit_views(id, views);
        if self.window().buffer() == id {
            self.follow_cursor();
        }
    }

    /// The native session buffers whose session has a turn under way or asks a question, in
    /// the order they were made: quitting when idle waits for them, as for a terminal's
    /// (ADR 0133).
    pub fn busy_native_sessions(&self) -> impl Iterator<Item = BufferId> + '_ {
        self.buffers
            .iter()
            .filter(|(_, buffer)| buffer.is_native_session() && buffer.is_busy())
            .map(|(id, _)| *id)
    }
}

/// Whether the session flags of a terminal (ADR 0121, 0132, 0133) apply to `buffer`: a
/// terminal's, or a native session's.
pub(in crate::editor) fn takes_session_flags(buffer: &Buffer) -> bool {
    buffer.is_terminal() || buffer.is_native_session()
}

